"""LLM result cache and the committed replay snapshot (plan 7.3, D18).

Key = SHA-256(request content) + prompt version + model id. The request content is the
canonical JSON of the messages sent (it holds the image bytes / texts), so any change to
the input, the prompt or the model gives a new key.

* The file cache (``.cache/llm/``, not committed) holds validated results of live calls.
* ``code/llm_snapshot.py`` holds the validated results of the final full run. With no
  key, or ``ZENMUX_OFFLINE=1``, the client replays it. It holds model output only: no
  human corrections, no request secrets (fixes go into prompts and validators).
"""

from __future__ import annotations

import hashlib
import json
import pprint
from pathlib import Path

import config


def content_hash(payload) -> str:
    if not isinstance(payload, (bytes, str)):
        payload = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    if isinstance(payload, str):
        payload = payload.encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def cache_key(payload, prompt_version: str, model: str) -> str:
    return f"{content_hash(payload)}:{prompt_version}:{model}"


def _file_name(key: str) -> str:
    return hashlib.sha256(key.encode("utf-8")).hexdigest() + ".json"


def load_snapshot() -> dict:
    try:
        import llm_snapshot
    except ImportError:
        return {}
    return dict(getattr(llm_snapshot, "SNAPSHOT", {}))


class LLMCache:
    def __init__(self, cache_dir: Path | None = config.CACHE_DIR, snapshot: dict | None = None):
        self.cache_dir = cache_dir
        self.snapshot = load_snapshot() if snapshot is None else snapshot
        self.used: dict[str, dict] = {}   # key -> record, every validated result this run returned

    def get(self, key: str) -> dict | None:
        if self.cache_dir is None:
            return None
        path = self.cache_dir / _file_name(key)
        if not path.is_file():
            return None
        record = json.loads(path.read_text(encoding="utf-8"))
        return record if record.get("key") == key else None

    def put(self, key: str, record: dict) -> None:
        record = {"key": key, **record}
        if self.cache_dir is not None:
            self.cache_dir.mkdir(parents=True, exist_ok=True)
            (self.cache_dir / _file_name(key)).write_text(
                json.dumps(record, sort_keys=True, ensure_ascii=False, indent=1), encoding="utf-8")

    def replay(self, key: str) -> dict | None:
        return self.snapshot.get(key)

    def mark_used(self, key: str, record: dict) -> None:
        self.used[key] = {"key": key, **{k: v for k, v in record.items() if k != "key"}}

    def export_snapshot(self, path: Path = config.SNAPSHOT_FILE) -> int:
        """Write every validated result used in this run to ``llm_snapshot.py``.

        Entries of the existing snapshot are kept (a sample run and the full run share one
        snapshot); an entry used in this run replaces the old one with the same key.
        """
        merged = {**self.snapshot, **self.used}
        entries = {k: merged[k] for k in sorted(merged)}
        body = pprint.pformat(entries, width=110, sort_dicts=True)
        path.write_text(
            '"""Validated model results of the final full run (generated by llm_cache.export_snapshot).\n\n'
            "Model output only: never edited by hand. Replayed when no API key is set or ZENMUX_OFFLINE=1.\n"
            '"""\n\n'
            f"MODEL = {config.MODEL_ID!r}\n"
            f"SNAPSHOT = {body}\n", encoding="utf-8")
        return len(entries)
