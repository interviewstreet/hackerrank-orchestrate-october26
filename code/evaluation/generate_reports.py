"""Regenerate evaluation_report.md and usage_report.md from a fresh full run.

Usage (repo root):  python3 code/evaluation/generate_reports.py
Every number in the reports is measured by this script; nothing is typed in by hand.
"""
from __future__ import annotations

import csv
import json
import os
import sys
import time
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "code"))
sys.path.insert(0, str(HERE))

from engine.case_analyzer import analyze_case, build_context        # noqa: E402
from engine.pipeline import run_cases                                # noqa: E402
from engine.validate_output import validate_output_csv               # noqa: E402
import custom_cases                                                  # noqa: E402
import invariants                                                    # noqa: E402
import importlib.util                                                # noqa: E402

_spec = importlib.util.spec_from_file_location("eval_main", HERE / "main.py")
_em = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_em)
evaluate, key, load_expected = _em.evaluate, _em.key, _em.load_expected


def pct(x):
    return f"{100 * x:.1f}%"


def main():
    t0 = time.perf_counter()
    ec = build_context(ROOT / "dataset")
    t_load = time.perf_counter() - t0
    t1 = time.perf_counter()
    full = run_cases(ec.ctx.requests, ec)
    t_run = time.perf_counter() - t1
    samples = run_cases(ec.ctx.sample_requests, ec)
    expected = load_expected(ROOT / "dataset" / "sample_output.csv")
    m = evaluate(samples, expected)

    # remaining differences on the public samples
    diffs = []
    for r in samples:
        est, esteps = expected[r.case_id]
        pk, ek = {key(s): s for s in r.steps}, {key(s): s for s in esteps}
        for k in ek:
            if k not in pk:
                diffs.append(f"{r.case_id}: missing {k[0].lower()} {k[2]} {k[3]}")
        for k in pk:
            if k not in ek:
                diffs.append(f"{r.case_id}: extra {k[0].lower()} {k[2]} {k[3]}")

    custom = custom_cases.run_all(ec)

    import tempfile
    sys.path.insert(0, str(ROOT / "code" / "tests"))
    from minidata import EXPECTED as mini_expected, build_mini_dataset
    mec = build_context(build_mini_dataset(tempfile.mkdtemp()))
    mini_got = {r["case_id"]: analyze_case(r, mec) for r in mec.ctx.requests}
    mini_ok = sum(mini_got[c].deletion_status == st and mini_got[c].steps == steps for c, (st, steps) in mini_expected.items())

    audit, captured = {}, {}
    for name in ("deletion_requests.csv", "sample_deletion_requests.csv"):
        with open(ROOT / "dataset" / name, encoding="utf-8", newline="") as fh:
            audit.update({r["case_id"]: r["audit_at"] for r in csv.DictReader(fh)})
    with open(ROOT / "dataset" / "evidence_files.csv", encoding="utf-8", newline="") as fh:
        captured = {r[0]: r[-1] for r in csv.reader(fh) if r and r[0].startswith("evidence_")}
    with open(ROOT / "output.csv", encoding="utf-8", newline="") as fh:
        violations = invariants.check_rows(csv.DictReader(fh), audit, captured)
    problems = validate_output_csv(ROOT / "output.csv", ROOT / "dataset")
    status = Counter(r.deletion_status for r in full)
    steps_total = sum(len(r.steps) for r in full)
    fa = m["field_accuracy"]

    ev = f"""# ERASIGHT Evaluation Report

Generated by `code/evaluation/generate_reports.py` from a fresh run; every figure below was measured, not typed in.
Reproduce: `python3 code/main.py` then `python3 code/evaluation/main.py` and `python3 code/evaluation/custom_cases.py`.

## 1. Approach in one paragraph
The agent is a deterministic evidence-reasoning pipeline (no model calls). It classifies whether deletion was actually
requested, resolves the customer's current and historical identifiers (exact matches only, so lookalikes are never merged),
normalises every evidence file (SQL snapshots of all replica types, JSON exports, four log layouts, PDFs, screenshots via OCR)
into time-stamped observations, reconstructs each resource's state **as of `audit_at`**, applies `deletion_rules.csv`, and emits
ordered findings, remediation and verification steps. Evidence is cited only if its file existed at `audit_at`.

## 2. Case-level status accuracy (32 public sample cases)
| Metric | Result |
|---|---|
| `deletion_status` accuracy | **{m['counts']['status_ok']}/{m['cases']} ({pct(m['status_accuracy'])})** |
| Exact-case match (every step identical and in order) | {m['counts']['exact_ok']}/{m['cases']} ({pct(m['exact_case_match'])}) |

## 3. Step-level accuracy
| Metric | Result |
|---|---|
| Step precision | {pct(m['step_precision'])} |
| Step recall | {pct(m['step_recall'])} |
| Step F1 | {pct(m['step_f1'])} |
| Steps matched / predicted / expected | {m['counts']['tp']} / {m['counts']['pred']} / {m['counts']['exp']} |

## 4. Field-level accuracy (over expected steps)
| Field | Accuracy |
|---|---|
""" + "\n".join(f"| `{k}` | {pct(v)} |" for k, v in fa.items()) + f"""

## 5. Sequence accuracy
Mean order similarity between predicted and expected step sequences (difflib ratio, per case): **{pct(m['sequence_similarity'])}**.

## 6. Full-dataset run (the run that produced `output.csv`)
- Requests processed: {len(full)}; `COMPLETE` {status['COMPLETE']}, `INCOMPLETE` {status['INCOMPLETE']}, `NOT_APPLICABLE` {status['NOT_APPLICABLE']}; {steps_total} steps in total.
- Structural validation (`validate_output_csv`): {'passed' if not problems else f'{len(problems)} problem(s)'}.
- Policy/time invariants over all rows (`invariants.py`: retained records never deleted, backups only blocked, flows only disabled,
  no remediation on COMPLETE, no evidence captured after `audit_at`, COMPLETE steps always cited): {'0 violations' if not violations else f'{len(violations)} violations'}.
- The same invariants hold for the public answer key, which confirms they are not artefacts of our output.

## 7. Additional evaluation cases written by the team
Each is derived from a public sample by a perturbation whose correct outcome follows from the problem statement.

| # | Case | Expected behaviour | Result |
|---|---|---|---|
""" + "\n".join(f"| {i} | `{c.name}` (from {c.base}) | {c.expectation} | {'PASS' if ok else 'FAIL'}: {detail} |"
                for i, (c, ok, detail) in enumerate(custom, 1)) + f"""

Run with `python3 code/evaluation/custom_cases.py`; they are also enforced by `pytest code/tests`.

### 7b. Self-contained mini dataset with hand-derived full answers
`code/tests/minidata.py` builds a tiny invented dataset (4 customers, 3 evidence files, 6 requests) and `test_mini_dataset.py`
checks every step of every case against an answer written by hand from `deletion_rules.csv` *before* the engine was run on it:
| Case | Situation | Expected |
|---|---|---|
| mini_01 | Leftover search entry, restorable backup, retained audit record | INCOMPLETE; report both, block restore, delete the entry, verify absent / present / blocked |
| mini_02 | Active data flow | INCOMPLETE; report, disable, verify disabled |
| mini_03 | Lookalike address `examp1e` of a real customer | INCOMPLETE, no steps invented |
| mini_04 | Request that declines deletion | NOT_APPLICABLE, no steps |
| mini_05 | Profile present in an old snapshot, absent from a later full snapshot | COMPLETE; cites the later snapshot (absent) and the retained audit record |
| mini_06 | Audit before any evidence existed | INCOMPLETE, no steps (nothing provable) |

Result: **{mini_ok}/{len(mini_expected)} exact** (`pytest code/tests/test_mini_dataset.py`).

## 8. Failures found and improvements made
| Failure found | Improvement |
|---|---|
| Spanish imperative "elimine mi cuenta" classified `NOT_APPLICABLE` (custom case) | Broadened the multilingual deletion lexicon to word stems (Spanish, French, Portuguese, Italian, German, Dutch, CJK) |
| Activity after `audit_at` could be used as evidence (custom case: audit moved before the worker ran) | Activity inference now ignores events later than `audit_at` |
| A case with evidence but nothing attributable returned `COMPLETE` with zero steps (case_61) | `COMPLETE` now requires at least one verified-compliant resource; otherwise nothing is proven |
| Evidence that only predates the request counted as the audit outcome (case_61, case_07) | Resources known only from pre-request evidence are not claimed (retained records, flows and backups exempt) |
| A screenshot naming two customers claimed the other customer's integration (case_15) | A resource explicitly tied to a different user is dropped |
| Snapshots omitting a retained audit record were read as "deleted" (cases 21, 25-28) | Retained categories never infer absence from a snapshot |
| Support PDF whose attachment is described on page 2 was treated as a message (case_07) | Attachment detection uses the whole document and file name |
| Two cases competing for the same worker activities (cases 25-28) | Deterministic ordering among cases sharing a report time; unowned analytics records go only to otherwise-complete cases |
| Early iterations: replica-blind absence, log layouts dropped, evidence cited from files captured after `audit_at` | Replica-aware absence, all four log layouts parsed, manifest capture time gates every citation |

## 9. Remaining differences on the public samples
""" + ("\n".join(f"- {d}" for d in diffs) if diffs else "None.") + """

## 10. Known limitations and assumptions
- Peer ordering (cases sharing a report time take worker activities in case order) and "unowned analytics records belong to otherwise-complete
  cases" were derived from the 32 samples; they are the least-proven rules for the other cases.
- `account_004`-style records that appear in no evidence or activity cannot be reported without guessing, so they are not.
- Hidden-answer behaviour for an unresolved identity (we return `INCOMPLETE` with no steps) is our reasoned choice.
- Optional advisory layer (`code/advisor/`): a language model may add a plain-language explanation and a review flag to cases that
  deterministic triggers mark as ambiguous (unresolved identity, possible lookalike email, mixed wording, no attributable records).
  It runs only with `python code/advise.py --model`, is checked so it cannot cite an id the engine did not produce, falls back to a
  template on any problem, and never changes `output.csv`. Unit tests use a fake model; no live-model evaluation has been run yet.
- The system has no learned component, so there is no training/test split; the samples were used to design rules, and the
  custom cases above plus the invariants are the independent checks.
"""
    (HERE / "evaluation_report.md").write_text(ev, encoding="utf-8")

    n = len(full)
    def _load(name):
        f = HERE / name
        return json.loads(f.read_text(encoding="utf-8")) if f.exists() else None

    main_run, demo_run = _load("advisor_usage.json"), _load("advisor_usage_demo.json")
    # The summary covers ONLY the final full-dataset run that produced output.csv. The mini-dataset demo is reported
    # separately and never added to the full-run totals or per-request averages.
    full = main_run if main_run and main_run["calls"] else None
    demo = demo_run if demo_run and demo_run["calls"] else None
    calls = full["calls"] if full else 0
    tin = full["input_tokens"] if full else 0
    tout = full["output_tokens"] if full else 0
    adv = full or demo
    # Estimated prices in USD per million tokens (Groq list price for openai/gpt-oss-120b, checked Nov 2026); override
    # with LLM_PRICE_INPUT_PER_MTOK / LLM_PRICE_OUTPUT_PER_MTOK if the rates change.
    pin = float(os.environ.get("LLM_PRICE_INPUT_PER_MTOK") or 0.15)
    pout = float(os.environ.get("LLM_PRICE_OUTPUT_PER_MTOK") or 0.60)

    def _cost(i, o):
        return i / 1e6 * pin + o / 1e6 * pout
    if full:
        total = _cost(tin, tout)
        cost, cost_req = f"${total:.4f}", f"${total / n:.6f}"
        per_call = f"{(tin + tout) / calls:.0f}"
    else:
        cost, cost_req, per_call = "$0.00", "$0.00", "n/a"
    if not full:
        who = ("**The full-dataset run made zero model calls.** The decisions are a deterministic pipeline (rules, parsers, local "
               "`pdftotext` and `tesseract` OCR). The optional advisory layer (`python code/advise.py --model`) was not used for "
               "that run, so there are no input or output tokens and no per-token cost.")
        model_rows = "| Model providers and names used at run time | None |"
        per_model = "No models were used in the full-dataset run, so there is no per-model table."
    else:
        who = (f"The decisions behind `output.csv` come from the deterministic engine and make **no model calls**. The optional advisory "
               f"layer (`python code/advise.py --model`) asked **{adv['provider']} / {adv['model']}** for a second opinion on cases the "
               f"deterministic triggers flagged. It only writes `explanations.json`; it cannot change `output.csv`. "
               f"The figures below are for that single full-dataset advisory run; the mini-dataset demo is listed separately and excluded.")
        model_rows = f"| Model providers and names used at run time | {adv['provider']}: {adv['model']} (advisory layer only) |"
        per_model = (f"| Model | Calls | Input tokens | Output tokens | Total tokens | Estimated cost |\n|---|---|---|---|---|---|\n"
                     f"| {adv['provider']} {adv['model']} (full-dataset run) | {calls} | {tin} | {tout} | {tin + tout} | {cost} |\n"
                     f"| **Overall (full-dataset run)** | {calls} | {tin} | {tout} | {tin + tout} | {cost} |")
    demo_section = ""
    if demo:
        dc = _cost(demo["input_tokens"], demo["output_tokens"])
        demo_section = (f"\n## Separate: mini-dataset demo (NOT part of the totals above)\n"
                        f"A lookalike-email demo on the small mini dataset, used only to show the advisory layer working. "
                        f"{demo['calls']} calls, {demo['input_tokens']} input and {demo['output_tokens']} output tokens "
                        f"({demo['input_tokens'] + demo['output_tokens']} total, about ${dc:.4f}).\n")
    us = f"""# ERASIGHT Token Usage and Cost Report

This report covers the final full-dataset run that produced `output.csv` ({n} requests).

## Summary
{who}

| Item | Value |
|---|---|
{model_rows}
| Model calls | {calls} |
| Input tokens | {tin} |
| Output tokens | {tout} |
| Total tokens | {tin + tout} |
| Average tokens per request (total tokens / {n} requests) | {(tin + tout) / n:.1f} |\n| Average tokens per model call | {per_call} |
| Estimated total cost | {cost} |\n| Price assumption (USD per million tokens) | input {pin:g}, output {pout:g} |
| Estimated cost per request | {cost_req} |

## Per-model breakdown
{per_model}
{demo_section}
## Run characteristics (measured)
| Item | Value |
|---|---|
| Requests | {n} |
| Dataset and evidence load | {t_load:.1f} s |
| Analysis of all requests | {t_run:.1f} s ({1000 * t_run / n:.1f} ms per request) |
| Network access by the decision pipeline | None |

## Note on development tooling
The code was written with an AI coding assistant (Claude Code). That usage is development tooling, not part of the
submitted agent's run, and is recorded in the session transcript (`log.txt`) rather than measured here.
To refresh this file after a model run: `python code/advise.py --model` then `python code/evaluation/generate_reports.py`.
"""
    (HERE / "usage_report.md").write_text(us, encoding="utf-8")
    print("wrote evaluation_report.md and usage_report.md")


if __name__ == "__main__":
    main()
