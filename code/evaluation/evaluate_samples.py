#!/usr/bin/env python3
"""Compare generated predictions with the public sample answer file."""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
STEP_FIELDS = (
    "step_no",
    "phase",
    "system_id",
    "resource_id",
    "operation",
    "state",
    "evidence_id",
)


def read_csv(path: Path) -> dict[str, dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as source:
        return {row["case_id"]: row for row in csv.DictReader(source)}


def parse_steps(row: dict[str, str]) -> list[dict[str, object]]:
    value = json.loads(row["steps_json"])
    if not isinstance(value, list):
        raise ValueError(f"steps_json for {row['case_id']} is not an array")
    return value


def signature(step: dict[str, object]) -> tuple[object, ...]:
    return tuple(step.get(field) for field in STEP_FIELDS[1:])


def evaluate(prediction_path: Path) -> dict[str, object]:
    expected = read_csv(ROOT / "dataset" / "sample_output.csv")
    predicted = read_csv(prediction_path)
    matched_ids = sorted(expected.keys() & predicted.keys())
    missing_ids = sorted(expected.keys() - predicted.keys())
    extra_ids = sorted(predicted.keys() - expected.keys())

    status_correct = sum(
        expected[case_id]["deletion_status"]
        == predicted[case_id]["deletion_status"]
        for case_id in matched_ids
    )
    exact_sequences = 0
    field_correct = 0
    field_total = 0
    expected_steps = 0
    predicted_steps = 0
    matched_steps = 0
    not_applicable_contract_ok = 0

    for case_id in matched_ids:
        expected_row = expected[case_id]
        predicted_row = predicted[case_id]
        expected_array = parse_steps(expected_row)
        predicted_array = parse_steps(predicted_row)
        expected_steps += len(expected_array)
        predicted_steps += len(predicted_array)
        if expected_array == predicted_array:
            exact_sequences += 1

        aligned = max(len(expected_array), len(predicted_array))
        field_total += aligned * len(STEP_FIELDS)
        for index in range(aligned):
            expected_step = expected_array[index] if index < len(expected_array) else {}
            predicted_step = predicted_array[index] if index < len(predicted_array) else {}
            field_correct += sum(
                expected_step.get(field) == predicted_step.get(field)
                for field in STEP_FIELDS
            )

        expected_signatures = Counter(signature(step) for step in expected_array)
        predicted_signatures = Counter(signature(step) for step in predicted_array)
        matched_steps += sum((expected_signatures & predicted_signatures).values())

        if expected_row["deletion_status"] == "NOT_APPLICABLE":
            not_applicable_contract_ok += (
                predicted_row["deletion_status"] == "NOT_APPLICABLE"
                and predicted_array == []
            )

    precision = matched_steps / predicted_steps if predicted_steps else 0.0
    recall = matched_steps / expected_steps if expected_steps else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {
        "public_cases": len(expected),
        "predictions": len(predicted),
        "matched_case_ids": len(matched_ids),
        "missing_case_ids": missing_ids,
        "extra_case_ids": extra_ids,
        "status_correct": status_correct,
        "status_accuracy": status_correct / len(expected) if expected else 0.0,
        "exact_sequences": exact_sequences,
        "sequence_accuracy": exact_sequences / len(expected) if expected else 0.0,
        "field_correct": field_correct,
        "field_total": field_total,
        "field_accuracy": field_correct / field_total if field_total else 0.0,
        "expected_steps": expected_steps,
        "predicted_steps": predicted_steps,
        "matched_steps": matched_steps,
        "step_precision": precision,
        "step_recall": recall,
        "step_f1": f1,
        "not_applicable_contract_ok": not_applicable_contract_ok,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--predictions",
        type=Path,
        default=ROOT / "output.csv",
        help="CSV generated by the agent",
    )
    args = parser.parse_args()
    print(json.dumps(evaluate(args.predictions.resolve()), indent=2))


if __name__ == "__main__":
    main()
